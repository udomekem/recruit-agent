def main() -> None:
    lines = [
        json.dumps({**ad, "agent": "rubric_builder", "label_source": "draft"}, ensure_ascii=False)
        for ad in ADS
    ]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(lines)} cases to {OUT.name}")


if __name__ == "__main__":
    main()
